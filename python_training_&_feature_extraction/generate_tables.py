import numpy as np
import librosa

# --- CONFIGURATION (MUST MATCH YOUR TRAINING DATA) ---
# Fixed from original: N_MELS/N_MFCC raised to 40 (standard for speech)
# Fixed from original: hop_length set to 10ms (160 samples) for proper time resolution
SAMPLE_RATE  = 16000
N_FFT        = 512        # Window size: 32ms @ 16kHz (standard)
HOP_LENGTH   = 160        # Hop size: 10ms @ 16kHz (standard)
N_MELS       = 40         # Mel bands (was 10, now 40 - industry standard)
N_MFCC       = 40         # MFCC features (was 10, now 40 - industry standard)
# -----------------------------------------------------

def print_array(f, name, array):
    """ Helper to write a numpy array as a C++ float array """
    f.write(f"const float {name}[{array.size}] = {{\n")
    for i, val in enumerate(array.flatten()):
        f.write(f"    {val:.6f}f, ")
        if (i+1) % 10 == 0:
            f.write("\n")
    f.write("};\n\n")

# 1. Hamming Window (FIXED: was np.hanning which is Hann, not Hamming)
# Hamming window has better sidelobe suppression for speech processing
window = np.hamming(N_FFT).astype(np.float32)

# 2. Mel Filterbank Matrix
# Maps the raw FFT (N_FFT/2+1 bins) -> Mel Scale (N_MELS bands)
# This mimics how the human ear groups frequencies.
mel_filters = librosa.filters.mel(
    sr=SAMPLE_RATE,
    n_fft=N_FFT,
    n_mels=N_MELS,
    dtype=np.float32
)

# 3. DCT Matrix (Discrete Cosine Transform)
# Decorrelates the data and compresses it.
# Built manually to ensure exact match with C++ inference.
n = np.arange(N_MELS)
k = np.arange(N_MFCC)[:, np.newaxis]
dct = np.cos(np.pi / N_MELS * (n + 0.5) * k)
dct[0] *= 1.0 / np.sqrt(2)
dct *= np.sqrt(2.0 / N_MELS)
dct = dct.astype(np.float32)

# --- WRITE THE C++ HEADER FILE ---
with open("mfcc_data.h", "w") as f:
    f.write("// AUTOMATICALLY GENERATED FILE. DO NOT EDIT.\n")
    f.write("// Generated by generate_tables.py\n")
    f.write("// Parameters: SR=16000, N_FFT=512, HOP=160, N_MELS=40, N_MFCC=40\n\n")
    f.write("#ifndef MFCC_DATA_H\n#define MFCC_DATA_H\n\n")

    # Save the dimensions so C++ knows loop limits
    f.write(f"#define N_FFT       {N_FFT}\n")
    f.write(f"#define HOP_LENGTH  {HOP_LENGTH}\n")
    f.write(f"#define N_MELS      {N_MELS}\n")
    f.write(f"#define N_MFCC      {N_MFCC}\n\n")

    # Write the 3 arrays
    print_array(f, "hamming_window", window)     # N_FFT values
    print_array(f, "mel_filters",    mel_filters) # N_MELS x (N_FFT/2+1) values
    print_array(f, "dct_matrix",     dct)         # N_MFCC x N_MELS values

    f.write("#endif\n")

print("Done! 'mfcc_data.h' has been generated.")
print(f"  Window:      Hamming, {N_FFT} points")
print(f"  Mel filters: {mel_filters.shape}")
print(f"  DCT matrix:  {dct.shape}")


