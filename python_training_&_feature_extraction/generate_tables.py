# VERIFICATION: Reproduce what librosa does so your Python
# training script can use the exact same logic.
# In your training script, call mfcc_from_audio() below
# instead of librosa.feature.mfcc() to guarantee a match.
# ---------------------------------------------------------------

def mfcc_from_audio(audio: np.ndarray) -> np.ndarray:
    """
    Compute MFCCs exactly matching the C++ mfcc_compute() function.
    Use this in your training/preprocessing pipeline.

    Parameters:
        audio:  1D float32 numpy array, mono, 16kHz
    Returns:
        mfcc:   2D array of shape (N_MFCC, num_frames)
    """
    # Step 1: Short-time Fourier Transform with Hamming window, POWER spectrum
    # power=2.0 -> |FFT|^2  (matches the C++ fix: r*r + im*im)
    S_power = np.abs(
        librosa.stft(
            audio,
            n_fft=N_FFT,
            hop_length=HOP_LENGTH,
            window='hamming',   # Must be Hamming to match C++
            center=False        # No zero-padding at edges (matches C++ frame-by-frame)
        )
    ) ** 2.0                    # POWER spectrum

    # Step 2: Mel filterbank
    mel_S = mel_filters @ S_power            # (N_MELS, frames)

    # Step 3: Log
    log_mel = np.log(mel_S + 1e-6)           # +1e-6 matches C++ floor

    # Step 4: DCT
    mfcc = dct @ log_mel                     # (N_MFCC, frames)

    return mfcc.astype(np.float32)


