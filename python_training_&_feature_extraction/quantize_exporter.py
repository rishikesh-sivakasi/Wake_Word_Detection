"""
quantize_exporter.py  (updated for embedding model)
====================================================
Exports the trained WakeWordEmbedder weights to a C++ header file.

What this does:
  - Conv/Linear weights → INT8 (saves memory on Pi)
  - BatchNorm parameters → FLOAT32 (must stay float for accuracy)
  - Writes weights_embedding.h for cnn_inference.cpp

HOW TO RUN:
  python3 quantize_exporter.py

INPUT:   embedding_model.pth   (from train_embedding.py)
OUTPUT:  weights_embedding.h   (goes on Raspberry Pi with other .h files)
"""

import torch
import numpy as np
from embedding_model import WakeWordEmbedder


# ══════════════════════════════════════════════════════════════════
# HELPERS
# ══════════════════════════════════════════════════════════════════

def quantize_to_int8(f, cpp_name, tensor):
    """Conv weight or Linear weight/bias → INT8 + scale"""
    np_arr   = tensor.detach().cpu().numpy().flatten()
    max_val  = np.max(np.abs(np_arr))
    scale    = max_val / 127.0 if max_val > 0 else 1.0
    q        = np.clip(np.round(np_arr / scale), -127, 127).astype(np.int8)

    f.write(f"const float   {cpp_name}_scale = {scale:.8f}f;\n")
    f.write(f"const int8_t  {cpp_name}[{len(q)}] = {{\n    ")
    f.write(", ".join(map(str, q)))
    f.write("\n};\n\n")


def export_float(f, cpp_name, tensor):
    """BatchNorm gamma/beta/running_mean/running_var → FLOAT32"""
    np_arr = tensor.detach().cpu().numpy().flatten()
    f.write(f"const float {cpp_name}[{len(np_arr)}] = {{\n    ")
    f.write(", ".join([f"{x:.8f}f" for x in np_arr]))
    f.write("\n};\n\n")


# ══════════════════════════════════════════════════════════════════
# MAIN
# ══════════════════════════════════════════════════════════════════

def main():
    print("Loading embedding model...")
    model = WakeWordEmbedder(embedding_dim=128)

    try:
        checkpoint = torch.load("embedding_model.pth", map_location="cpu", weights_only=False)
        model.load_state_dict(checkpoint["model_state"])
    except FileNotFoundError:
        print("ERROR: embedding_model.pth not found!")
        print("Run train_embedding.py first.")
        return

    model.eval()
    state = model.state_dict()

    print("Exporting weights to weights_embedding.h ...")

    with open("weights_embedding.h", "w") as f:
        f.write("// ==========================================================\n")
        f.write("// weights_embedding.h\n")
        f.write("// Auto-generated by quantize_exporter.py\n")
        f.write("// Conv/Linear: INT8   |   BatchNorm: FLOAT32\n")
        f.write("// ==========================================================\n\n")
        f.write("#ifndef WEIGHTS_EMBEDDING_H\n")
        f.write("#define WEIGHTS_EMBEDDING_H\n\n")
        f.write("#include <stdint.h>\n\n")

        for name, param in state.items():
            cpp_name = name.replace(".", "_")

            # ── Detect layer type ─────────────────────────────────
            # BatchNorm params: weight(gamma), bias(beta), running_mean, running_var
            # Everything else: Conv weight, Linear weight, Linear bias → INT8

            is_bn = (
                "running_mean"  in name or
                "running_var"   in name or
                "num_batches"   in name or
                # BatchNorm weight/bias: their parent module has running_mean
                any(
                    name.replace(".weight", ".running_mean") in state or
                    name.replace(".bias",   ".running_mean") in state
                    for _ in [None]   # just to use any()
                )
            )

            # Simpler detection: BN layers are always 1D with specific suffixes
            is_bn_param = (
                name.endswith(".running_mean") or
                name.endswith(".running_var")  or
                name.endswith("num_batches_tracked") or
                # features.1 = BN after conv1, features.5 = BN after conv2, etc.
                any(f"features.{i}." in name for i in [1, 5, 9])
            )

            if is_bn_param or "num_batches" in name:
                if "num_batches" not in name:  # skip the counter
                    export_float(f, cpp_name, param)
            else:
                # Conv weights and projector (Linear) weights/biases → INT8
                quantize_to_int8(f, cpp_name, param)

        f.write("#endif // WEIGHTS_EMBEDDING_H\n")

    # ── Report ────────────────────────────────────────────────────
    total_params = sum(p.numel() for p in model.parameters())
    float_kb     = total_params * 4 / 1024
    int8_kb      = total_params * 1 / 1024

    print("\n=== EXPORT COMPLETE ===")
    print(f"  Output:           weights_embedding.h")
    print(f"  Total parameters: {total_params:,}")
    print(f"  Original size:    ~{float_kb:.1f} KB  (float32)")
    print(f"  Quantized size:   ~{int8_kb:.1f} KB  (int8, ~75% smaller)")
    print("\nNext steps:")
    print("  1. Copy weights_embedding.h to your Raspberry Pi project folder")
    print("  2. Copy template.npy to your Raspberry Pi")
    print("  3. Recompile: g++ -O2 wake_word_detector.cpp cnn_inference.cpp mfcc.cpp \\")
    print("                    kissfft/kiss_fft.c -Ikissfft -lasound -o wake_word_detector")
    print("  4. Run: ./wake_word_detector template.npy")


if __name__ == "__main__":
    main()
